def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(
        description="Run CPython 3.14.9's Lib/test suite against PyX (differential oracle).",
    )
    ap.add_argument("--source", metavar="PATH", help="CPython 3.14.9 source tree (default: .pyx/cpython cache)")
    ap.add_argument("--cpython", metavar="PATH", help="CPython 3.14.9 executable (default: $PYX_CPYTHON, uv python find 3.14.9)")
    ap.add_argument("--pyx", help="path to the PyX binary (default: $PYX_BIN, release, debug)")
    ap.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT, help="per-run timeout in seconds")
    ap.add_argument("--only", help="comma-separated test names (with or without .py)")
    ap.add_argument("--limit", type=int, help="run at most N tests (smoke runs)")
    ap.add_argument("--json", metavar="PATH", help=f"JSON output path (default: {DEFAULT_JSON})")
    ap.add_argument("--md", metavar="PATH", help=f"Markdown output path (default: {DEFAULT_MD})")
    modes = ap.add_mutually_exclusive_group()
    modes.add_argument(
        "--update-manifest",
        nargs="?",
        const=str(DEFAULT_MANIFEST),
        default=None,
        metavar="PATH",
        help=f"write the passing set to a manifest (default: {DEFAULT_MANIFEST})",
    )
    modes.add_argument(
        "--gate",
        nargs="?",
        const=str(DEFAULT_MANIFEST),
        default=None,
        metavar="PATH",
        help=f"run the suite and enforce a manifest (default: {DEFAULT_MANIFEST})",
    )
    modes.add_argument(
        "--check-manifest",
        nargs="?",
        const=str(DEFAULT_MANIFEST),
        default=None,
        metavar="PATH",
        help="validate a manifest offline (default: tests/compat/cpython-3.14.9.json)",
    )
    return ap.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    if args.timeout <= 0:
        log("error: --timeout must be positive")
        return 1
    if args.limit is not None and args.limit < 0:
        log("error: --limit must be non-negative")
        return 1

    if args.check_manifest is not None:
        path = Path(args.check_manifest).expanduser()
        manifest, error = load_manifest(path)
        if error:
            log(f"error: {error}")
            return 1
        problems = validate_manifest(manifest or {})
        if problems:
            log(f"manifest invalid: {path}")
            for problem in problems:
                log(f"  - {problem}")
            return 1
        log(f"manifest ok: {path} ({manifest_summary(manifest or {})})")
        return 0

    full_run_required = args.gate is not None or args.update_manifest is not None
    if full_run_required and (args.only or args.limit is not None):
        log("error: --gate and --update-manifest require a full run; drop --only/--limit")
        return 1

    pyx, pyx_error = resolve_pyx(args.pyx)
    if pyx is None:
        log(f"error: {pyx_error}")
        return 2

    cpython, cpython_version, cpython_error = resolve_cpython(args.cpython)
    if cpython is None or cpython_version is None:
        log(f"error: {cpython_error}")
        return 2

    source, source_error = resolve_source(args.source, allow_download=args.gate is None)
    if source is None:
        log(f"error: {source_error}")
        return 2

    env = dict(os.environ)
    env["BROWSER"] = "true"  # keep `import antigravity`/webbrowser from opening a window
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env.setdefault("NO_COLOR", "1")
    cpython_env = dict(env)
    cpython_env["PYTHONPATH"] = str(source / "Lib")
    pyx_env = dict(env)
    pyx_env.pop("PYTHONPATH", None)  # the oracle's path must not leak into PyX

    test_dir = source / "Lib" / "test"
    paths, unknown = discover_tests(test_dir, args.only, args.limit)
    for name in unknown:
        log(f"warning: test not found in {test_dir}: {name}")
    if not paths:
        log(f"error: no test_*.py selected in {test_dir}")
        return 1

    json_path = Path(args.json).expanduser() if args.json else DEFAULT_JSON
    md_path = Path(args.md).expanduser() if args.md else DEFAULT_MD

    tests: list[dict] = []
    started = time.perf_counter()
    for index, path in enumerate(paths, 1):
        log(f"[{index}/{len(paths)}] {path.name}")
        tests.append(check_test(path, source, cpython, pyx, args.timeout, cpython_env, pyx_env))

    counts = summarize(tests)
    elapsed = round(time.perf_counter() - started, 1)
    date = utc_now()

    only = sorted(part.strip() for part in args.only.split(",") if part.strip()) if args.only else None
    meta = {
        "date": date,
        "python_target": TARGET_PYTHON,
        "cpython": {"path": str(cpython), "version": cpython_version},
        "pyx": {"path": str(pyx), "version": pyx_version(pyx)},
        "source": str(source),
        "options": {"timeout": args.timeout, "limit": args.limit, "only": only},
        "cwd": str(ROOT),
        "elapsed_seconds": elapsed,
    }

    payload = {
        "meta": meta,
        "summary": counts,
        "passing": sorted(test["name"] for test in tests if test["status"] == PASS_STATUS),
        "tests": tests,
    }
    body = render_body(meta, tests, counts)

    write_text(json_path, json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
    write_text(md_path, render_document(md_path, body))

    log(
        f"tests: {counts['total']} ({counts['passed']} passing, {counts['failed']} failing) "
        f"in {elapsed:g}s -> {json_path}, {md_path}"
    )
    for status in FAIL_STATUSES:
        if counts["by_status"][status]:
            log(f"  {status}: {counts['by_status'][status]}")

    if args.update_manifest is not None:
        manifest_path = Path(args.update_manifest).expanduser()
        existing: dict | None = None
        if manifest_path.exists():
            existing, error = load_manifest(manifest_path)
            if error:
                log(f"error: {error}")
                return 1
            problems = validate_manifest(existing or {})
            if problems:
                log(f"error: refusing to update an invalid manifest: {manifest_path}")
                for problem in problems:
                    log(f"  - {problem}")
                return 1
        passing = {test["name"] for test in tests if test["status"] == PASS_STATUS}
        manifest, error = build_updated_manifest(existing, passing, date)
        if error:
            log(f"error: {error}")
            return 1
        assert manifest is not None
        write_text(manifest_path, json.dumps(manifest, indent=2) + "\n")
        log(f"manifest written: {manifest_path} ({manifest_summary(manifest)})")
        return 0

    if args.gate is not None:
        manifest_path = Path(args.gate).expanduser()
        manifest, error = load_manifest(manifest_path)
        if error:
            log(f"error: {error}")
            return 1
        assert manifest is not None
        problems = evaluate_gate(manifest, tests)
        if problems:
            log(f"gate FAILED: {manifest_path}")
            for problem in problems:
                log(f"  - {problem}")
            return 1
        log(
            f"gate ok: {manifest_path} ({counts['passed']} passing, "
            f"minimum {manifest['minimum_passing']}, "
            f"{len(manifest['required'])} required)"
        )
        return 0

    return 0


def pyx_version(pyx: Path) -> str:
    result = run_capture([str(pyx), "--version"], cwd=ROOT, timeout=VERSION_TIMEOUT)
    text = (result["stdout"] or "").strip() or (result["stderr"] or "").strip()
    first = text.splitlines()[0].strip() if text else ""
    return first or "unknown"


if __name__ == "__main__":
    sys.exit(main())
