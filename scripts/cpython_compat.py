HERE = Path(__file__).resolve().parent
ROOT = HERE.parent  # repository root (parent of scripts/)

TARGET_PYTHON = "3.14.9"
DOWNLOAD_URL = f"https://www.python.org/ftp/python/{TARGET_PYTHON}/Python-{TARGET_PYTHON}.tgz"
CACHE_ROOT = ROOT / ".pyx" / "cpython"
DEFAULT_SOURCE = CACHE_ROOT / f"Python-{TARGET_PYTHON}"
DEFAULT_ARCHIVE = CACHE_ROOT / f"Python-{TARGET_PYTHON}.tgz"

DEFAULT_JSON = ROOT / "benchmarks" / "compat" / f"cpython-{TARGET_PYTHON}.json"
DEFAULT_MD = ROOT / "docs" / "CPYTHON_TESTS.md"
DEFAULT_MANIFEST = ROOT / "tests" / "compat" / f"cpython-{TARGET_PYTHON}.json"

DEFAULT_TIMEOUT = 30.0
VERSION_TIMEOUT = 30.0
DOWNLOAD_TIMEOUT = 120.0
MAX_ERROR_CHARS = 300
MAX_MD_ERROR_CHARS = 110

MANIFEST_NOTES = (
    "Release gate; grow as stdlib/language support lands. "
    "Import-only baseline is separate in docs/COMPATIBILITY.md."
)

PASS_STATUS = "pyx_pass"
FAIL_STATUSES = ("pyx_fail", "cpython_fail", "expected_fail", "timeout")
STATUSES = (PASS_STATUS, *FAIL_STATUSES)

ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")
PYX_CODE_RE = re.compile(r"error\[(PYX\d+)\]")
EXCEPTION_RE = re.compile(
    r"^(?:[A-Za-z_][\w.]*)(?:Error|Exception|Warning|Exit|Interrupt)\b"
)

MARKER_BEGIN = "<!-- BEGIN GENERATED RESULTS -->"
MARKER_END = "<!-- END GENERATED RESULTS -->"

HEADER = """\
# CPython test suite gate

Generated by `scripts/cpython_compat.py`; the policy, commands and pinning
rules are documented in `docs/CPYTHON_TESTS.md`.
"""


# --------------------------------------------------------------------- helpers
def log(message: str) -> None:
    print(message, file=sys.stderr, flush=True)


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def resolve_pyx(cli_value: str | None) -> tuple[Path | None, str | None]:
    """Resolve the PyX binary; an explicit --pyx path must be usable."""
    if cli_value:
        candidate = Path(cli_value).expanduser()
        if not (candidate.is_file() and os.access(candidate, os.X_OK)):
            return None, f"PyX binary not found or not executable: {candidate}"
        return candidate.resolve(), None
    env = os.environ.get("PYX_BIN")
    if env:
        candidate = Path(env).expanduser()
        if not (candidate.is_file() and os.access(candidate, os.X_OK)):
            return None, f"$PYX_BIN is not an executable file: {candidate}"
        return candidate.resolve(), None
    for candidate in (ROOT / "target" / "release" / "pyx", ROOT / "target" / "debug" / "pyx"):
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return candidate.resolve(), None
    return None, (
        "PyX binary not found (tried --pyx, $PYX_BIN, "
        f"{ROOT / 'target' / 'release' / 'pyx'}, {ROOT / 'target' / 'debug' / 'pyx'})"
    )


def run_capture(
    cmd: list[str],
    *,
    cwd: Path,
    timeout: float,
    env: dict[str, str] | None = None,
) -> dict:
    """Run a command once; never raises for a failing/timing-out program."""
    started = time.perf_counter()
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(cwd),
            capture_output=True,
            text=True,
            timeout=timeout,
            stdin=subprocess.DEVNULL,
            env=env,
        )
        return {
            "exit": proc.returncode,
            "stdout": proc.stdout or "",
            "stderr": proc.stderr or "",
            "timed_out": False,
            "duration_ms": round((time.perf_counter() - started) * 1000.0, 1),
        }
    except subprocess.TimeoutExpired:
        return {
            "exit": None,
            "stdout": "",
            "stderr": "",
            "timed_out": True,
            "duration_ms": round((time.perf_counter() - started) * 1000.0, 1),
        }
    except OSError as exc:
        return {
            "exit": None,
            "stdout": "",
            "stderr": str(exc),
            "timed_out": False,
            "duration_ms": round((time.perf_counter() - started) * 1000.0, 1),
        }


def version_from_output(text: str) -> str:
    line = (text or "").strip().splitlines()[0].strip() if (text or "").strip() else ""
    if line.startswith("Python "):
        line = line[len("Python ") :]
    return line.strip()


def executable_version(exe: Path) -> tuple[str | None, str]:
    """Return (version, detail) for an interpreter; version is None on failure."""
    result = run_capture(
        [str(exe), "--version"],
        cwd=ROOT,
        timeout=VERSION_TIMEOUT,
    )
    text = (result["stdout"] or "").strip() or (result["stderr"] or "").strip()
    if result["timed_out"]:
        return None, f"{exe} --version timed out"
    if result["exit"] != 0:
        return None, f"{exe} --version failed (exit {result['exit']}): {text[:200]}"
    version = version_from_output(text)
    if not version:
        return None, f"{exe} --version produced no version string"
    return version, text.splitlines()[0].strip()


def uv_python_find() -> tuple[Path | None, str]:
    uv = shutil.which("uv")
    if not uv:
        return None, "uv is not installed"
    result = run_capture(
        [uv, "python", "find", TARGET_PYTHON],
        cwd=ROOT,
        timeout=VERSION_TIMEOUT,
    )
    if result["timed_out"]:
        return None, "`uv python find` timed out"
    if result["exit"] != 0:
        detail = (result["stderr"] or result["stdout"] or "").strip().splitlines()
        tail = detail[-1] if detail else f"exit {result['exit']}"
        return None, f"`uv python find {TARGET_PYTHON}` failed: {tail}"
    first = next((line.strip() for line in (result["stdout"] or "").splitlines() if line.strip()), "")
    if not first:
        return None, f"`uv python find {TARGET_PYTHON}` returned no path"
    return Path(first).expanduser(), "uv python find"


def resolve_cpython(cli_value: str | None) -> tuple[Path | None, str | None, str | None]:
    """Resolve and verify the pinned CPython oracle.

    Returns (path, version, error).  An explicit interpreter is verified just
    like the uv-resolved default: the oracle is pinned to 3.14.9.
    """
    candidate: Path | None = None
    origin = ""
    if cli_value:
        candidate = Path(cli_value).expanduser()
        origin = "--cpython"
        if not (candidate.is_file() and os.access(candidate, os.X_OK)):
            return None, None, f"--cpython is not an executable file: {candidate}"
    else:
        env = os.environ.get("PYX_CPYTHON")
        if env:
            candidate = Path(env).expanduser()
            origin = "$PYX_CPYTHON"
            if not (candidate.is_file() and os.access(candidate, os.X_OK)):
                return None, None, f"$PYX_CPYTHON is not an executable file: {candidate}"
        else:
            candidate, origin = uv_python_find()
            if candidate is None:
                return None, None, (
                    f"CPython {TARGET_PYTHON} oracle not found ({origin}). "
                    f"Install it with `uv python install {TARGET_PYTHON}`, or pass "
                    "--cpython PATH / set $PYX_CPYTHON."
                )
            if not (candidate.is_file() and os.access(candidate, os.X_OK)):
                return None, None, (
                    f"{origin} resolved to {candidate}, which is not an executable file. "
                    f"Install it with `uv python install {TARGET_PYTHON}` or pass --cpython PATH."
                )

    version, detail = executable_version(candidate)
    if version is None:
        return None, None, f"cannot use CPython oracle {candidate} ({origin}): {detail}"
    if not version.startswith(TARGET_PYTHON):
        return None, version, (
            f"CPython oracle {candidate} ({origin}) reports {detail!r}; this harness "
            f"pins {TARGET_PYTHON}. Install the pinned interpreter with "
            f"`uv python install {TARGET_PYTHON}` or pass --cpython PATH."
        )
    return candidate.resolve(), version, None


def source_version(src: Path) -> str | None:
    patchlevel = src / "Include" / "patchlevel.h"
    if not patchlevel.is_file():
        return None
    try:
        text = patchlevel.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    parts: list[str] = []
    for key in ("PY_MAJOR_VERSION", "PY_MINOR_VERSION", "PY_MICRO_VERSION"):
        match = re.search(rf"#define\s+{key}\s+(\d+)", text)
        if not match:
            return None
        parts.append(match.group(1))
    return ".".join(parts)


def verify_source(src: Path) -> str | None:
    """Return an error string when *src* is not a usable CPython 3.14.9 tree."""
    test_dir = src / "Lib" / "test"
    if not test_dir.is_dir():
        return f"not a CPython source tree (missing Lib/test): {src}"
    if not any(test_dir.glob("test_*.py")):
        return f"not a CPython source tree (no Lib/test/test_*.py): {src}"
    version = source_version(src)
    if version is None:
        return (
            f"cannot determine the CPython version of {src} "
            "(Include/patchlevel.h is missing or unreadable)"
        )
    if version != TARGET_PYTHON:
        return (
            f"CPython source tree {src} is {version}; this harness pins "
            f"{TARGET_PYTHON}. Use --source with a {TARGET_PYTHON} tree."
        )
    return None


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def download_source() -> Path:
    """Download and extract the pinned CPython source into the cache."""
    dest = DEFAULT_SOURCE
    CACHE_ROOT.mkdir(parents=True, exist_ok=True)

    if not DEFAULT_ARCHIVE.is_file():
        log(f"downloading {DOWNLOAD_URL}")
        partial = DEFAULT_ARCHIVE.with_name(DEFAULT_ARCHIVE.name + ".part")
        try:
            with urllib.request.urlopen(DOWNLOAD_URL, timeout=DOWNLOAD_TIMEOUT) as response:
                with partial.open("wb") as handle:
                    shutil.copyfileobj(response, handle)
        except (OSError, urllib.error.URLError) as exc:
            partial.unlink(missing_ok=True)
            raise RuntimeError(f"failed to download {DOWNLOAD_URL}: {exc}") from exc
        os.replace(partial, DEFAULT_ARCHIVE)
    log(f"sha256 {sha256_file(DEFAULT_ARCHIVE)}  {DEFAULT_ARCHIVE}")

    if (dest / "Lib" / "test").is_dir():
        return dest
    if dest.exists():
        raise RuntimeError(
            f"cached source {dest} exists but is incomplete (missing Lib/test); "
            f"remove it and retry, or pass --source PATH"
        )

    tmpdir = Path(tempfile.mkdtemp(prefix="extract-", dir=str(CACHE_ROOT)))
    try:
        try:
            with tarfile.open(DEFAULT_ARCHIVE, "r:gz") as archive:
                try:
                    archive.extractall(tmpdir, filter="data")
                except TypeError:  # Python < 3.12 has no extraction filters
                    archive.extractall(tmpdir)
        except (OSError, tarfile.TarError) as exc:
            raise RuntimeError(f"failed to extract {DEFAULT_ARCHIVE}: {exc}") from exc
        extracted = tmpdir / f"Python-{TARGET_PYTHON}"
        if not (extracted / "Lib" / "test").is_dir():
            raise RuntimeError(
                f"{DEFAULT_ARCHIVE} did not contain Python-{TARGET_PYTHON}/Lib/test"
            )
        os.replace(extracted, dest)
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)
    return dest


def resolve_source(cli_value: str | None, *, allow_download: bool) -> tuple[Path | None, str | None]:
    """Resolve the CPython source tree; never downloads when disabled."""
    if cli_value:
        src = Path(cli_value).expanduser()
        if not src.is_dir():
            return None, f"--source is not a directory: {src}"
        src = src.resolve()
    elif (DEFAULT_SOURCE / "Lib" / "test").is_dir():
        src = DEFAULT_SOURCE
        log(f"using cached CPython source: {src}")
    elif allow_download:
        try:
            src = download_source()
        except RuntimeError as exc:
            return None, str(exc)
    else:
        return None, (
            f"CPython {TARGET_PYTHON} source not found at {DEFAULT_SOURCE} and "
            "this mode does not download. Run the harness once without --gate "
            f"to populate the cache, or pass --source PATH."
        )

    error = verify_source(src)
    if error:
        return None, error
    return src, None


# -------------------------------------------------------------------- discovery
def discover_tests(test_dir: Path, only: str | None, limit: int | None) -> tuple[list[Path], list[str]]:
    paths = sorted(
        (path for path in test_dir.glob("test_*.py") if path.is_file()),
        key=lambda path: path.name,
    )
    unknown: list[str] = []
    if only:
        wanted = {part.strip() for part in only.split(",") if part.strip()}
        normalized = {name[:-3] if name.endswith(".py") else name for name in wanted}
        available = {path.stem for path in paths}
        unknown = sorted(normalized.difference(available))
        paths = [path for path in paths if path.stem in normalized]
    if limit is not None:
        paths = paths[:limit]
    return paths, unknown


# -------------------------------------------------------------------- execution
def last_non_empty_line(text: str) -> str:
    for line in reversed((text or "").splitlines()):
        stripped = line.strip()
        if stripped:
            return stripped
    return ""


def first_error(stderr: str, stdout: str) -> str | None:
    """First ``error[PYXnnnn]`` line, else the first exception line."""
    text = ANSI_RE.sub("", stderr or "")
    for line in text.splitlines():
        if PYX_CODE_RE.search(line):
            return line.strip()[:MAX_ERROR_CHARS]
    for line in text.splitlines():
        stripped = line.strip()
        if EXCEPTION_RE.match(stripped):
            return stripped[:MAX_ERROR_CHARS]
    tail = last_non_empty_line(text) or last_non_empty_line(ANSI_RE.sub("", stdout or ""))
    return tail[:MAX_ERROR_CHARS] or None


def classify(cpython: dict, pyx: dict) -> str:
    """Differential status; a PyX timeout is never a pass."""
    if pyx["timed_out"]:
        return "timeout"
    if cpython["timed_out"]:
        return "expected_fail" if pyx["exit"] != 0 else "cpython_fail"
    if cpython["exit"] == 0:
        return PASS_STATUS if pyx["exit"] == 0 else "pyx_fail"
    return "expected_fail" if pyx["exit"] != 0 else "cpython_fail"


def check_test(
    path: Path,
    source: Path,
    cpython: Path,
    pyx: Path,
    timeout: float,
    cpython_env: dict[str, str],
    pyx_env: dict[str, str],
) -> dict:
    lib_dir = source / "Lib"
    cpython_run = run_capture(
        [str(cpython), str(path)],
        cwd=lib_dir,
        timeout=timeout,
        env=cpython_env,
    )
    pyx_run = run_capture(
        [str(pyx), "run", "--color=never", str(path)],
        cwd=ROOT,
        timeout=timeout,
        env=pyx_env,
    )
    status = classify(cpython_run, pyx_run)

    error: str | None = None
    if status != PASS_STATUS:
        if pyx_run["timed_out"]:
            error = f"PyX timed out after {timeout:g}s"
        else:
            error = first_error(pyx_run["stderr"], pyx_run["stdout"])
            if not error:
                error = first_error(cpython_run["stderr"], cpython_run["stdout"])

    return {
        "name": path.name,
        "status": status,
        "cpython": {
            "exit": cpython_run["exit"],
            "timed_out": cpython_run["timed_out"],
            "duration_ms": cpython_run["duration_ms"],
        },
        "pyx": {
            "exit": pyx_run["exit"],
            "timed_out": pyx_run["timed_out"],
            "duration_ms": pyx_run["duration_ms"],
        },
        "error": error,
    }


# ---------------------------------------------------------------------- reports
def summarize(tests: list[dict]) -> dict:
    by_status = Counter(test["status"] for test in tests)
    counts = {status: by_status.get(status, 0) for status in STATUSES}
    passed = counts[PASS_STATUS]
    return {
        "total": len(tests),
        "passed": passed,
        "failed": len(tests) - passed,
        "by_status": counts,
    }


def md_cell(value: object, limit: int | None = None) -> str:
    text = " ".join(str(value).split())
    if limit is not None and len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text.replace("|", "\\|") or "-"


def run_cell(run: dict) -> str:
    if run["timed_out"]:
        label = "timeout"
    elif run["exit"] == 0:
        label = "ok"
    else:
        label = f"exit {run['exit']}"
    return f"{label} / {run['duration_ms']:g} ms"


def render_body(meta: dict, tests: list[dict], counts: dict) -> str:
    cpython = meta["cpython"]
    pyx = meta["pyx"]
    out: list[str] = []
    out.append(
        f"Environment: CPython `{cpython['version']}` (`{cpython['path']}`) · "
        f"PyX `{pyx['version']}` (`{pyx['path']}`)"
    )
    out.append("")
    out.append(f"Source: `{meta['source']}` · generated {meta['date']}")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| Status | Tests |")
    out.append("| --- | ---: |")
    for status in STATUSES:
        out.append(f"| {status} | {counts['by_status'][status]} |")
    out.append(f"| **Total** | {counts['total']} |")
    out.append("")
    out.append(
        f"Passing: **{counts['passed']} / {counts['total']}** "
        "(a pass requires PyX and CPython 3.14.9 to both exit 0)."
    )
    out.append("")

    out.append("## Passing tests")
    out.append("")
    passing = sorted(test["name"] for test in tests if test["status"] == PASS_STATUS)
    if passing:
        out.extend(f"- `{name}`" for name in passing)
    else:
        out.append(
            "No tests pass yet. This is expected while the stdlib and unittest "
            "prerequisites are missing; do not add tests to the manifest's "
            "`required` list until they genuinely pass."
        )
    out.append("")

    out.append("## Failure classes")
    out.append("")
    failures = [
        (status, counts["by_status"][status])
        for status in FAIL_STATUSES
        if counts["by_status"][status]
    ]
    if failures:
        out.append("| Status | Tests |")
        out.append("| --- | ---: |")
        for status, count in sorted(failures, key=lambda item: (-item[1], item[0])):
            out.append(f"| {status} | {count} |")
    else:
        out.append("No failing tests.")
    out.append("")

    out.append("## Test results")
    out.append("")
    out.append("| Test | CPython 3.14.9 | PyX | Status | First error |")
    out.append("| --- | --- | --- | --- | --- |")
    for test in tests:
        out.append(
            f"| `{md_cell(test['name'])}` | {run_cell(test['cpython'])} | "
            f"{run_cell(test['pyx'])} | {md_cell(test['status'])} | "
            f"{md_cell(test['error'] or '-', MAX_MD_ERROR_CHARS)} |"
        )
    out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_document(md_path: Path, body: str) -> str:
    """Splice the generated block, preserving the policy prose when present."""
    try:
        existing = md_path.read_text(encoding="utf-8") if md_path.is_file() else ""
    except OSError:
        existing = ""
    if MARKER_BEGIN in existing and MARKER_END in existing:
        before = existing[: existing.index(MARKER_BEGIN)]
        after = existing[existing.index(MARKER_END) + len(MARKER_END) :]
        return f"{before}{MARKER_BEGIN}\n\n{body}\n{MARKER_END}{after}"
    header = existing.rstrip() + "\n\n" if existing.strip() else HEADER
    return f"{header}{MARKER_BEGIN}\n\n{body}\n{MARKER_END}\n"


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


# --------------------------------------------------------------------- manifest
def load_manifest(path: Path) -> tuple[dict | None, str | None]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None, f"manifest not found: {path}"
    except (OSError, ValueError) as exc:
        return None, f"cannot read manifest {path}: {exc}"
    if not isinstance(data, dict):
        return None, f"manifest {path} must contain a JSON object"
    return data, None


def validate_manifest(data: dict) -> list[str]:
    """Structural, offline validation of a manifest v1 document."""
    problems: list[str] = []
    python = data.get("python")
    if python != TARGET_PYTHON:
        problems.append(f"python must be {TARGET_PYTHON!r} (found {python!r})")

    minimum = data.get("minimum_passing")
    if isinstance(minimum, bool) or not isinstance(minimum, int) or minimum < 0:
        problems.append(f"minimum_passing must be a non-negative integer (found {minimum!r})")
        minimum = None

    lists: dict[str, list[str]] = {}
    for key in ("required", "known_passing"):
        value = data.get(key)
        if not isinstance(value, list) or not all(isinstance(item, str) and item for item in value):
            problems.append(f"{key} must be a list of test file names")
            continue
        if len(set(value)) != len(value):
            problems.append(f"{key} contains duplicates")
        bad = sorted(item for item in value if not item.startswith("test_") or not item.endswith(".py"))
        if bad:
            problems.append(f"{key} must contain top-level test_*.py names: {', '.join(bad)}")
        lists[key] = value

    notes = data.get("notes", "")
    if not isinstance(notes, str):
        problems.append("notes must be a string")

    if "required" in lists and "known_passing" in lists:
        missing = sorted(set(lists["required"]).difference(lists["known_passing"]))
        if missing:
            problems.append(
                "required tests missing from known_passing: " + ", ".join(missing)
            )
        if minimum is not None and minimum > len(lists["known_passing"]):
            problems.append(
                f"minimum_passing ({minimum}) exceeds known_passing "
                f"({len(lists['known_passing'])})"
            )
    return problems


def manifest_summary(data: dict) -> str:
    return (
        f"python={data.get('python')!r}, minimum_passing={data.get('minimum_passing')}, "
        f"known_passing={len(data.get('known_passing') or [])}, "
        f"required={len(data.get('required') or [])}"
    )


def build_updated_manifest(existing: dict | None, passing: set[str], date: str) -> tuple[dict | None, str | None]:
    known = sorted(passing)
    required = sorted(existing.get("required") or []) if existing else []
    old_minimum = existing.get("minimum_passing", 0) if existing else 0
    if isinstance(old_minimum, bool) or not isinstance(old_minimum, int):
        old_minimum = 0
    notes = existing.get("notes", MANIFEST_NOTES) if existing else MANIFEST_NOTES

    stale = sorted(set(required).difference(known))
    if stale:
        return None, (
            "refusing to write the manifest: required tests no longer pass: "
            + ", ".join(stale)
            + ". Fix the regressions or remove them from `required` deliberately."
        )
    if old_minimum > len(known):
        return None, (
            f"refusing to write the manifest: minimum_passing is {old_minimum} but only "
            f"{len(known)} tests pass. This is a regression; do not lower the gate silently."
        )
    return (
        {
            "python": TARGET_PYTHON,
            "minimum_passing": max(old_minimum, len(known)),
            "required": required,
            "known_passing": known,
            "notes": notes,
            "generated": date,
        },
        None,
    )


def evaluate_gate(manifest: dict, tests: list[dict]) -> list[str]:
    problems = validate_manifest(manifest)
    if problems:
        return problems

    by_name = {test["name"]: test for test in tests}
    required = manifest["required"]
    missing = [name for name in required if name not in by_name]
    failing = [
        f"{name} ({by_name[name]['status']})"
        for name in required
        if name in by_name and by_name[name]["status"] != PASS_STATUS
    ]
    if missing:
        problems.append("required tests absent from this run: " + ", ".join(missing))
    if failing:
        problems.append("required tests not passing: " + ", ".join(failing))

    passed = sum(1 for test in tests if test["status"] == PASS_STATUS)
    minimum = manifest["minimum_passing"]
    if minimum > passed:
        problems.append(f"only {passed} tests pass, manifest requires at least {minimum}")
    return problems


