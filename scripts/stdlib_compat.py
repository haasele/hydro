#!/usr/bin/env python3
"""Compare CPython and PyX standard-library import support.

For every name in ``sys.stdlib_module_names`` a temporary script containing
``import <name>`` is executed by the CPython oracle and by PyX (``pyx run``).
Failures are classified, timed out runs are recorded as data and the result is
written as JSON plus a Markdown report.

    python3 scripts/stdlib_compat.py
    python3 scripts/stdlib_compat.py --only json,os --limit 10
    python3 scripts/stdlib_compat.py --pyx ../target/debug/pyx --timeout 5
    python3 scripts/stdlib_compat.py --cpython /path/to/python3.14
    python3 scripts/stdlib_compat.py --tests /path/to/cpython/Lib/test

The CPython oracle is resolved from ``--cpython``, ``$PYX_CPYTHON`` or
``uv python find 3.14.9``.  It is verified to report 3.14.9; if that fails the
script falls back to ``sys.executable`` with a prominent warning that the
oracle is not the pinned patch version (the report marks ``python_pinned``).
The PyX binary is resolved from ``--pyx``, ``$PYX_BIN``, ``target/release/pyx``
or ``target/debug/pyx`` (relative to the repository root).  Exit code 0 means
the report was produced, 2 means the PyX binary was not found.  Performance
numbers are not measured here; import success is not test-suite success.
"""

from __future__ import annotations

import argparse
import importlib.machinery
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent  # repository root (parent of scripts/)

DEFAULT_JSON = ROOT / "benchmarks" / "compat" / "latest.json"
DEFAULT_MD = ROOT / "docs" / "COMPATIBILITY.md"

TARGET_PYTHON = "3.14.9"
DEFAULT_TIMEOUT = 10.0
VERSION_TIMEOUT = 10.0
MAX_ERROR_CHARS = 300
MAX_MD_ERROR_CHARS = 90

LAYERS = ("builtin/frozen", "pure", "extension", "unknown")
ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")
PYX_CODE_RE = re.compile(r"error\[(PYX\d+)\]")
TRACEBACK_MARKER = "Traceback (most recent call last)"

MARKER_BEGIN = "<!-- BEGIN GENERATED TABLE -->"
MARKER_END = "<!-- END GENERATED TABLE -->"

HEADER = """\
# PyX standard library compatibility

Status of the CPython standard library under PyX. The module matrix below is
generated by `scripts/stdlib_compat.py`; do not edit the generated block by
hand. **Target: CPython 3.14.9** (3.13 is security-only; 3.15 is newer than the
supported oracle; see `docs/CPYTHON_TESTS.md`).

```sh
python3 scripts/stdlib_compat.py
```

The script imports every name in `sys.stdlib_module_names` once under the
CPython oracle and once under PyX (`pyx run`), each in a fresh process with
a timeout. The oracle is `--cpython`, `$PYX_CPYTHON`, or
`uv python find 3.14.9`; it must report 3.14.9 unless the harness explicitly
warns that it fell back to `sys.executable`. A module counts as **importable**
when CPython imports it and `pyx run` exits 0 within the timeout. Failures are
classified as compile errors (`error[PYXnnnn]`), runtime errors (`Traceback`),
timeouts, or `cpython_failed` (the harness interpreter cannot import the module
either).

**Import success is not test-suite success.** An importable module may expose
only a subset of its API, may behave differently, or may fail as soon as a
function is called. The table makes no claim about semantics or test coverage.
CPython's own `Lib/test` suite is the reference for behavioural compatibility;
`scripts/stdlib_compat.py --tests <dir>` is the hook for running such a
checkout, and a test is only reported as passing when CPython and PyX agree.

Machine-readable results are written to `benchmarks/compat/latest.json`.
"""


# --------------------------------------------------------------------- helpers
def log(message: str) -> None:
    print(message, file=sys.stderr, flush=True)


def resolve_pyx(cli_value: str | None) -> tuple[Path | None, str | None]:
    """Resolve the PyX binary; an explicit --pyx path must be usable."""
    if cli_value:
        candidate = Path(cli_value).expanduser()
        if not (candidate.is_file() and os.access(candidate, os.X_OK)):
            return None, f"PyX binary not found or not executable: {candidate}"
        return candidate.resolve(), None
    env = os.environ.get("PYX_BIN")
    if env:
        candidate = Path(env).expanduser()
        if not (candidate.is_file() and os.access(candidate, os.X_OK)):
            return None, f"$PYX_BIN is not an executable file: {candidate}"
        return candidate.resolve(), None
    for candidate in (ROOT / "target" / "release" / "pyx", ROOT / "target" / "debug" / "pyx"):
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return candidate.resolve(), None
    return None, (
        "PyX binary not found (tried --pyx, $PYX_BIN, "
        f"{ROOT / 'target' / 'release' / 'pyx'}, {ROOT / 'target' / 'debug' / 'pyx'})"
    )


def pyx_version(pyx: Path) -> str:
    try:
        proc = subprocess.run(
            [str(pyx), "--version"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=VERSION_TIMEOUT,
            stdin=subprocess.DEVNULL,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    text = (proc.stdout or "").strip() or (proc.stderr or "").strip()
    first = text.splitlines()[0].strip() if text else ""
    return first or "unknown"


def cpython_version(executable: Path) -> str | None:
    """Return the oracle's version (e.g. ``3.14.9``) or None."""
    try:
        proc = subprocess.run(
            [str(executable), "--version"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=VERSION_TIMEOUT,
            stdin=subprocess.DEVNULL,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    text = (proc.stdout or "").strip() or (proc.stderr or "").strip()
    first = text.splitlines()[0].strip() if text else ""
    if first.startswith("Python "):
        first = first[len("Python ") :].strip()
    return first or None


def _uv_python_find() -> tuple[Path | None, str]:
    uv = shutil.which("uv")
    if not uv:
        return None, "uv is not installed"
    try:
        proc = subprocess.run(
            [uv, "python", "find", TARGET_PYTHON],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=VERSION_TIMEOUT,
            stdin=subprocess.DEVNULL,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return None, f"cannot run `uv python find`: {exc}"
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or "").strip().splitlines()
        tail = detail[-1] if detail else f"exit {proc.returncode}"
        return None, f"`uv python find {TARGET_PYTHON}` failed: {tail}"
    first = next(
        (line.strip() for line in (proc.stdout or "").splitlines() if line.strip()),
        "",
    )
    if not first:
        return None, f"`uv python find {TARGET_PYTHON}` returned no path"
    candidate = Path(first).expanduser()
    if not (candidate.is_file() and os.access(candidate, os.X_OK)):
        return None, f"uv returned a non-executable path: {candidate}"
    return candidate, ""


def resolve_cpython(cli_value: str | None) -> tuple[Path | None, str | None, str | None]:
    """Return (oracle, version, error); the oracle is pinned to 3.14.9.

    An explicit ``--cpython``/``$PYX_CPYTHON`` is never silently replaced by a
    different interpreter. Only the implicit uv lookup falls back to
    ``sys.executable``, and it always warns.
    """
    explicit = cli_value or os.environ.get("PYX_CPYTHON")
    if explicit:
        origin = "--cpython" if cli_value else "$PYX_CPYTHON"
        candidate = Path(explicit).expanduser()
        if not (candidate.is_file() and os.access(candidate, os.X_OK)):
            return None, None, f"{origin} is not an executable file: {candidate}"
        version = cpython_version(candidate)
        if version is None:
            return None, None, f"cannot determine the version of {origin} {candidate}"
        if not version.startswith(TARGET_PYTHON):
            return None, version, (
                f"{origin} {candidate} reports {version}; this project pins "
                f"CPython {TARGET_PYTHON}. Install it with "
                f"`uv python install {TARGET_PYTHON}` or select the pinned interpreter."
            )
        return candidate.resolve(), version, None

    candidate, reason = _uv_python_find()
    if candidate is not None:
        version = cpython_version(candidate)
        if version is not None and version.startswith(TARGET_PYTHON):
            return candidate.resolve(), version, None
        reason = f"{candidate} reports {version or 'an unknown version'}"
    else:
        reason = reason or "uv lookup failed"

    fallback = Path(sys.executable)
    version = cpython_version(fallback) or "unknown"
    if version.startswith(TARGET_PYTHON):
        log(
            f"warning: falling back to sys.executable ({fallback}) because {reason}; "
            f"it happens to match the CPython {TARGET_PYTHON} pin"
        )
    else:
        log(
            f"warning: CPython {TARGET_PYTHON} oracle unavailable ({reason}); falling "
            f"back to sys.executable ({fallback}, version {version}), which is NOT the "
            f"pinned patch version. Install it with `uv python install {TARGET_PYTHON}` "
            "or pass --cpython PATH."
        )
    return fallback, version, None


def module_layer(name: str) -> str:
    """Classify a stdlib module by its CPython origin."""
    try:
        spec = importlib.util.find_spec(name)
    except (ImportError, ValueError, AttributeError):
        return "unknown"
    if spec is None:
        return "unknown"
    origin = spec.origin or ""
    if origin in ("built-in", "frozen") or isinstance(
        spec.loader, (importlib.machinery.BuiltinImporter, importlib.machinery.FrozenImporter)
    ):
        return "builtin/frozen"
    if not origin:
        return "unknown"
    if any(origin.endswith(suffix) for suffix in importlib.machinery.EXTENSION_SUFFIXES):
        return "extension"
    return "pure"


def run_process(cmd: list[str], timeout: float, env: dict[str, str]) -> dict:
    """Run a command once; never raises for a failing/timing-out program."""
    started = time.perf_counter()
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=timeout,
            stdin=subprocess.DEVNULL,
            env=env,
        )
        return {
            "exit": proc.returncode,
            "stdout": proc.stdout or "",
            "stderr": proc.stderr or "",
            "timed_out": False,
            "duration_ms": round((time.perf_counter() - started) * 1000.0, 1),
        }
    except subprocess.TimeoutExpired:
        return {
            "exit": None,
            "stdout": "",
            "stderr": "",
            "timed_out": True,
            "duration_ms": round((time.perf_counter() - started) * 1000.0, 1),
        }
    except OSError as exc:
        return {
            "exit": None,
            "stdout": "",
            "stderr": str(exc),
            "timed_out": False,
            "duration_ms": round((time.perf_counter() - started) * 1000.0, 1),
        }


def last_non_empty_line(text: str) -> str:
    for line in reversed((text or "").splitlines()):
        stripped = line.strip()
        if stripped:
            return stripped
    return ""


def extract_error(stderr: str, stdout: str, tmpdir: str) -> tuple[str | None, str]:
    """Return (PYX code, human-readable first error) for a PyX run."""
    text = ANSI_RE.sub("", stderr or "")
    code: str | None = None
    message = ""
    match = PYX_CODE_RE.search(text)
    if match:
        code = match.group(1)
        for line in text.splitlines():
            if match.group(0) in line:
                message = line.strip()
                break
    if not message and TRACEBACK_MARKER in text:
        message = last_non_empty_line(text)
    if not message:
        message = last_non_empty_line(text) or last_non_empty_line(stdout or "")
    if tmpdir:
        message = message.replace(tmpdir, "<tmp>")
    return code, message[:MAX_ERROR_CHARS]


def classify(cpython: dict, pyx: dict) -> str:
    """Overall module status; CPython failures make the row incomparable."""
    if cpython["timed_out"] or cpython["exit"] != 0:
        return "cpython_failed"
    if pyx["timed_out"]:
        return "timeout"
    if pyx["exit"] == 0:
        return "ok"
    if pyx.get("code"):
        return f"compile_error:{pyx['code']}"
    return "runtime_error"


# ------------------------------------------------------------------- execution
def check_module(
    name: str,
    script: Path,
    cpython: Path,
    pyx: Path,
    timeout: float,
    env: dict[str, str],
) -> dict:
    script.write_text(f"import {name}\n", encoding="utf-8")

    cpython_run = run_process([str(cpython), str(script)], timeout, env)
    pyx_run = run_process([str(pyx), "run", "--color=never", str(script)], timeout, env)

    code, message = (None, "")
    if not pyx_run["timed_out"] and pyx_run["exit"] != 0:
        code, message = extract_error(pyx_run["stderr"], pyx_run["stdout"], str(script.parent))
    elif pyx_run["timed_out"]:
        code, message = None, f"timeout after {timeout:g}s"
    pyx_run["code"] = code

    status = classify(cpython_run, pyx_run)
    if status == "cpython_failed" and not message:
        cpy_line = last_non_empty_line(cpython_run["stderr"])
        if cpython_run["timed_out"]:
            message = f"CPython timeout after {timeout:g}s"
        elif cpy_line:
            message = cpy_line[:MAX_ERROR_CHARS]

    return {
        "name": name,
        "layer": module_layer(name),
        "cpython": {
            "exit": cpython_run["exit"],
            "ok": cpython_run["exit"] == 0 and not cpython_run["timed_out"],
            "timed_out": cpython_run["timed_out"],
            "duration_ms": cpython_run["duration_ms"],
        },
        "pyx": {
            "exit": pyx_run["exit"],
            "ok": pyx_run["exit"] == 0 and not pyx_run["timed_out"],
            "timed_out": pyx_run["timed_out"],
            "duration_ms": pyx_run["duration_ms"],
            "error": message or None,
        },
        "status": status,
        "error": message or None,
    }


def check_test(
    path: Path,
    cpython: Path,
    pyx: Path,
    timeout: float,
    env: dict[str, str],
) -> dict:
    cpython_run = run_process([str(cpython), str(path)], timeout, env)
    pyx_run = run_process([str(pyx), "run", "--color=never", str(path)], timeout, env)

    if cpython_run["timed_out"] or cpython_run["exit"] != 0:
        status = "expected_fail"
    elif pyx_run["timed_out"] or pyx_run["exit"] != 0:
        status = "pyx_fail"
    else:
        status = "ok"

    message = ""
    if status != "ok":
        _, message = extract_error(pyx_run["stderr"], pyx_run["stdout"], str(path.parent))
        if not message:
            message = last_non_empty_line(pyx_run["stderr"]) or last_non_empty_line(cpython_run["stderr"])

    return {
        "name": path.name,
        "path": str(path),
        "cpython_exit": cpython_run["exit"],
        "cpython_timed_out": cpython_run["timed_out"],
        "pyx_exit": pyx_run["exit"],
        "pyx_timed_out": pyx_run["timed_out"],
        "status": status,
        "expected_fail": status == "expected_fail",
        "error": message[:MAX_ERROR_CHARS] or None,
    }


# --------------------------------------------------------------------- reports
def summarize(modules: list[dict]) -> dict:
    by_status = Counter(row["status"] for row in modules)
    by_layer: dict[str, dict[str, int]] = {}
    for layer in LAYERS:
        rows = [row for row in modules if row["layer"] == layer]
        if not rows:
            continue
        ok = sum(1 for row in rows if row["status"] == "ok")
        by_layer[layer] = {"total": len(rows), "ok": ok, "failed": len(rows) - ok}
    total = len(modules)
    ok = by_status.get("ok", 0)
    return {
        "total": total,
        "ok": ok,
        "failed": total - ok,
        "by_status": dict(sorted(by_status.items())),
        "by_layer": by_layer,
    }


def md_cell(value: object, limit: int | None = None) -> str:
    text = " ".join(str(value).split())
    if limit is not None and len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text.replace("|", "\\|") or "-"


def exit_cell(run: dict) -> str:
    if run.get("timed_out"):
        return "timeout"
    if run.get("exit") == 0:
        return "ok"
    if run.get("exit") is None:
        return "spawn error"
    return f"exit {run['exit']}"


def render_module_table(modules: list[dict]) -> list[str]:
    lines = ["| Module | CPython | PyX | Status | Error |", "| --- | --- | --- | --- | --- |"]
    for row in modules:
        lines.append(
            "| `{name}` | {cpython} | {pyx} | {status} | {error} |".format(
                name=md_cell(row["name"]),
                cpython=exit_cell(row["cpython"]),
                pyx=exit_cell(row["pyx"]),
                status=md_cell(row["status"]),
                error=md_cell(row["error"] or "-", MAX_MD_ERROR_CHARS),
            )
        )
    return lines


def render_markdown(meta: dict, modules: list[dict], tests: list[dict], counts: dict) -> str:
    out: list[str] = []
    out.append(
        f"Environment: {meta['python']} (`{meta['python_executable']}`) · "
        f"PyX `{meta['pyx']['version']}` · binary `{meta['pyx']['path']}`"
    )
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| Layer | Modules | Importable | Failed |")
    out.append("| --- | ---: | ---: | ---: |")
    for layer in LAYERS:
        stats = counts["by_layer"].get(layer)
        if stats:
            out.append(f"| {layer} | {stats['total']} | {stats['ok']} | {stats['failed']} |")
    out.append(f"| **Total** | {counts['total']} | {counts['ok']} | {counts['failed']} |")
    out.append("")

    out.append("## Failure classes")
    out.append("")
    failures = {status: n for status, n in counts["by_status"].items() if status != "ok"}
    if failures:
        out.append("| Status | Count |")
        out.append("| --- | ---: |")
        for status, n in sorted(failures.items(), key=lambda item: (-item[1], item[0])):
            out.append(f"| {md_cell(status)} | {n} |")
    else:
        out.append("No failures.")
    out.append("")

    out.append("## Modules by layer")
    out.append("")
    for layer in LAYERS:
        rows = [row for row in modules if row["layer"] == layer]
        if not rows:
            continue
        out.append(f"### {layer} ({len(rows)})")
        out.append("")
        out.extend(render_module_table(rows))
        out.append("")

    if tests:
        out.append("## CPython test files (`--tests`)")
        out.append("")
        out.append(
            "A test is reported as `ok` only when CPython and PyX both exit 0; "
            "`expected_fail` means CPython fails on the harness, "
            "`pyx_fail` means the failure is PyX-specific."
        )
        out.append("")
        out.append("| Test | CPython | PyX | Status | Error |")
        out.append("| --- | --- | --- | --- | --- |")
        for test in tests:
            cpy = "timeout" if test["cpython_timed_out"] else (
                "ok" if test["cpython_exit"] == 0 else f"exit {test['cpython_exit']}"
            )
            px = "timeout" if test["pyx_timed_out"] else (
                "ok" if test["pyx_exit"] == 0 else f"exit {test['pyx_exit']}"
            )
            out.append(
                f"| `{md_cell(test['name'])}` | {cpy} | {px} | "
                f"{md_cell(test['status'])} | "
                f"{md_cell(test['error'] or '-', MAX_MD_ERROR_CHARS)} |"
            )
        out.append("")

    return "\n".join(out).rstrip() + "\n"


def write_report(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


# ------------------------------------------------------------------------ main
def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(
        description="Compare CPython and PyX stdlib import support.",
    )
    ap.add_argument("--pyx", help="path to the PyX binary (default: $PYX_BIN, release, debug)")
    ap.add_argument(
        "--cpython",
        metavar="PATH",
        help=f"CPython oracle executable, pinned to {TARGET_PYTHON} "
        "(default: $PYX_CPYTHON, uv python find, then sys.executable with a warning)",
    )
    ap.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT, help="per-run timeout in seconds")
    ap.add_argument("--json", metavar="PATH", help=f"JSON output path (default: {DEFAULT_JSON})")
    ap.add_argument("--md", metavar="PATH", help=f"Markdown output path (default: {DEFAULT_MD})")
    ap.add_argument("--only", help="comma-separated module names to check")
    ap.add_argument("--limit", type=int, help="check at most N modules/tests (smoke runs)")
    ap.add_argument("--tests", metavar="DIR", help="also run each test_*.py in DIR under both interpreters")
    return ap.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    if args.timeout <= 0:
        log("error: --timeout must be positive")
        return 1
    if args.limit is not None and args.limit < 0:
        log("error: --limit must be non-negative")
        return 1

    pyx, pyx_error = resolve_pyx(args.pyx)
    if pyx is None:
        log(f"error: {pyx_error}")
        return 2

    cpython, cpython_version, cpython_error = resolve_cpython(args.cpython)
    if cpython is None or cpython_version is None:
        log(f"error: {cpython_error}")
        return 2
    if not cpython_version.startswith(TARGET_PYTHON):
        log(
            f"warning: oracle {cpython} is CPython {cpython_version}; the report is not "
            f"pinned to {TARGET_PYTHON}"
        )

    if not hasattr(sys, "stdlib_module_names"):
        log("error: sys.stdlib_module_names requires Python 3.10+")
        return 1

    names = sorted(sys.stdlib_module_names)
    if args.only:
        wanted = {part.strip() for part in args.only.split(",") if part.strip()}
        unknown = sorted(wanted.difference(names))
        if unknown:
            log(f"warning: not in sys.stdlib_module_names: {', '.join(unknown)}")
        names = [name for name in names if name in wanted]
    if args.limit is not None:
        names = names[: args.limit]

    env = dict(os.environ)
    env["BROWSER"] = "true"  # keep `import antigravity` from opening a browser
    env.setdefault("NO_COLOR", "1")

    json_path = Path(args.json) if args.json else DEFAULT_JSON
    md_path = Path(args.md) if args.md else DEFAULT_MD

    modules: list[dict] = []
    tests: list[dict] = []
    started = time.perf_counter()

    with tempfile.TemporaryDirectory(prefix="pyx-compat-") as tmp:
        script = Path(tmp) / "check.py"
        for name in names:
            log(f"[{len(modules) + 1}/{len(names)}] {name}")
            modules.append(check_module(name, script, cpython, pyx, args.timeout, env))

    if args.tests:
        test_dir = Path(args.tests).expanduser().resolve()
        if not test_dir.is_dir():
            log(f"error: --tests directory not found: {test_dir}")
            return 1
        test_paths = sorted(test_dir.glob("test_*.py"))
        if args.limit is not None:
            test_paths = test_paths[: args.limit]
        for index, path in enumerate(test_paths, 1):
            log(f"[test {index}/{len(test_paths)}] {path.name}")
            tests.append(check_test(path, cpython, pyx, args.timeout, env))

    counts = summarize(modules)
    elapsed = round(time.perf_counter() - started, 1)

    meta = {
        "date": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "python": f"CPython {cpython_version}",
        "python_version": cpython_version,
        "python_executable": str(cpython),
        "python_target": TARGET_PYTHON,
        "python_pinned": cpython_version.startswith(TARGET_PYTHON),
        "pyx": {"path": str(pyx), "version": pyx_version(pyx)},
        "options": {
            "timeout": args.timeout,
            "limit": args.limit,
            "only": sorted(part.strip() for part in args.only.split(",") if part.strip())
            if args.only
            else None,
            "tests": str(Path(args.tests).resolve()) if args.tests else None,
        },
        "cwd": str(ROOT),
        "elapsed_seconds": elapsed,
        "counts": counts,
    }

    payload = {"meta": meta, "modules": modules}
    if args.tests:
        payload["tests"] = tests
        payload["meta"]["test_counts"] = dict(sorted(Counter(t["status"] for t in tests).items()))

    body = render_markdown(meta, modules, tests, counts)
    document = f"{HEADER}\n{MARKER_BEGIN}\n\n{body}\n{MARKER_END}\n"

    write_report(json_path, json.dumps(payload, indent=2, ensure_ascii=False) + "\n")
    write_report(md_path, document)

    log(
        f"modules: {counts['total']} ({counts['ok']} importable, {counts['failed']} failed) "
        f"in {elapsed:g}s -> {json_path}, {md_path}"
    )
    if args.tests:
        log(f"tests: {len(tests)} -> " + ", ".join(f"{k}={v}" for k, v in payload["meta"]["test_counts"].items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
