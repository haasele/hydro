//! `pyx completions`: print a shell completion script on stdout.
//!
//! The scripts are static: they are generated once here, so `pyx completions`
//! stays deterministic and dependency-free. Every subcommand and option listed
//! by [`crate::cli::usage_text`] is covered.

use std::ffi::OsString;
use std::process::ExitCode;

use crate::cli::{CliError, CliResult};

/// Shells with a bundled completion script, in documentation order.
const SHELLS: [&str; 3] = ["bash", "zsh", "fish"];

fn supported_shells() -> String {
    SHELLS.join(", ")
}

fn usage_error(message: String) -> CliError {
    CliError::usage(format!(
        "{message}\nsupported shells: {}",
        supported_shells()
    ))
}

pub(crate) fn cmd_completions(args: &[OsString]) -> CliResult {
    let (shell, extra) = match args {
        [] => return Err(usage_error(String::from("pyx: completions: missing shell"))),
        [shell, rest @ ..] => (shell.to_string_lossy(), rest.first()),
    };
    if let Some(extra) = extra {
        return Err(usage_error(format!(
            "pyx: completions: unexpected argument '{}'",
            extra.to_string_lossy()
        )));
    }

    let script = match shell.as_ref() {
        "bash" => BASH,
        "zsh" => ZSH,
        "fish" => FISH,
        other => {
            return Err(usage_error(format!(
                "pyx: completions: unsupported shell '{other}'"
            )))
        }
    };
    print!("{script}");
    Ok(ExitCode::SUCCESS)
}

const BASH: &str = r#"# bash completion for pyx (generated by `pyx completions bash`).
#
# Install:  pyx completions bash > /etc/bash_completion.d/pyx
#       or: source <(pyx completions bash)
#
# commands: new init check run build test pytest fmt lint clean doctor gc repl
#           add remove sync lock completions help
# options:  --json --color --no-color --verbose --quiet -o --output
#           --runtime-lib --no-cache --force --check --dry-run
#           --no-echo --no-banner -c -i --help -h --version -V

_pyx() {
    local cur prev commands options
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    commands="new init check run build test pytest fmt lint clean doctor gc repl add remove sync lock completions help"
    options="--json --color --no-color --verbose --quiet --no-echo --no-banner --help -h --version -V"

    case "$prev" in
        --color)
            COMPREPLY=( $(compgen -W "auto always never" -- "$cur") )
            return 0
            ;;
        -o|--output|--runtime-lib)
            COMPREPLY=( $(compgen -f -- "$cur") )
            return 0
            ;;
    esac

    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=( $(compgen -W "$commands -c -i --help -h --version -V" -- "$cur") )
        return 0
    fi

    case "${COMP_WORDS[1]}" in
        completions)
            COMPREPLY=( $(compgen -W "bash zsh fish" -- "$cur") )
            return 0
            ;;
        help)
            COMPREPLY=( $(compgen -W "$commands" -- "$cur") )
            return 0
            ;;
        new|init)
            COMPREPLY=( $(compgen -W "--force" -- "$cur") )
            COMPREPLY+=( $(compgen -d -- "$cur") )
            return 0
            ;;
        build)
            COMPREPLY=( $(compgen -W "$options -o --output --runtime-lib --no-cache" -- "$cur") )
            return 0
            ;;
        fmt)
            COMPREPLY=( $(compgen -W "$options --check" -- "$cur") )
            return 0
            ;;
        clean)
            COMPREPLY=( $(compgen -W "--dry-run" -- "$cur") )
            return 0
            ;;
        repl)
            COMPREPLY=( $(compgen -W "$options --no-echo --no-banner" -- "$cur") )
            return 0
            ;;
        doctor)
            COMPREPLY=( $(compgen -W "--json --no-color" -- "$cur") )
            return 0
            ;;
        add|remove|sync|lock)
            # all arguments are forwarded verbatim to uv
            return 0
            ;;
        pytest)
            COMPREPLY=( $(compgen -W "$options -q -x -k --maxfail" -- "$cur") )
            return 0
            ;;
    esac

    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "$options" -- "$cur") )
        return 0
    fi
    if [[ "$cur" != "" ]]; then
        COMPREPLY=( $(compgen -f -- "$cur") )
    fi
    return 0
}

complete -F _pyx pyx
"#;

const ZSH: &str = r#"#compdef pyx
# zsh completion for pyx (generated by `pyx completions zsh`).
#
# Install: pyx completions zsh > "${fpath[1]}/_pyx"
#
# commands: new init check run build test pytest fmt lint clean doctor gc repl
#           add remove sync lock completions help
# options:  --json --color --no-color --verbose --quiet -o --output
#           --runtime-lib --no-cache --force --check --dry-run
#           --no-echo --no-banner -c -i --help -h --version -V

_pyx() {
    local -a commands options
    commands=(
        'new:create a project directory with a minimal scaffold'
        'init:scaffold a project in an existing directory'
        'check:parse and type-check only'
        'run:compile with the JIT and run'
        'repl:run a persistent interpreter session'
        'gc:run and report GC statistics'
        'build:compile and link a native executable'
        'test:run test_*.py / *_test.py files'
        'pytest:run pytest-style tests, one process per file'
        'fmt:strip trailing whitespace and fix the final newline'
        'lint:type-check every .py file in the given paths'
        'clean:remove .pyx/cache and target/pyx-tmp'
        'doctor:report toolchain and environment status'
        'add:add dependencies with uv'
        'remove:remove dependencies with uv'
        'sync:sync the environment with uv'
        'lock:update the lockfile with uv'
        'completions:print a shell completion script'
        'help:show help'
    )
    options=(--json --color --no-color --verbose --quiet --no-echo --no-banner --help -h --version -V)

    if (( CURRENT == 2 )); then
        _describe -t commands 'pyx command' commands
        return
    fi

    case $words[2] in
        completions)
            _values 'shell' bash zsh fish
            return
            ;;
        help)
            _describe -t commands 'pyx command' commands
            return
            ;;
        new|init)
            _arguments '--force[overwrite existing non-empty files]' '*:directory:_files -/'
            return
            ;;
        build)
            _arguments \
                '--no-cache[do not read or write the build cache]' \
                '(-o --output)'{-o,--output}'[output path]:output path:_files' \
                '--runtime-lib[path to libpyx_runtime.a]:runtime library:_files' \
                '--json[print diagnostics as a JSON array]' \
                '--color[colorize diagnostics]:when:(auto always never)' \
                '--no-color[disable colors]' \
                '*:source file:_files'
            return
            ;;
        fmt)
            _arguments \
                '--check[report files that need formatting, do not write]' \
                '--json[print diagnostics as a JSON array]' \
                '--color[colorize diagnostics]:when:(auto always never)' \
                '--no-color[disable colors]' \
                '*:path:_files -/'
            return
            ;;
        clean)
            _arguments '--dry-run[report what would be removed]'
            return
            ;;
        repl)
            _arguments \
                '--no-echo[do not echo expression values]' \
                '--no-banner[do not print the version banner]' \
                '--quiet[suppress the banner and prompts]' \
                '--json[print diagnostics as a JSON array]' \
                '--color[colorize diagnostics]:when:(auto always never)' \
                '--no-color[disable colors]'
            return
            ;;
        doctor)
            _arguments '--json[print the report as one JSON object]' '--no-color[disable colors]'
            return
            ;;
        add|remove|sync|lock)
            # all arguments are forwarded verbatim to uv
            _files
            return
            ;;
        pytest)
            _arguments \
                '-q[quiet: one character per test]' \
                '-x[stop after the first failure]' \
                '--maxfail=[stop after N failures]:count:' \
                '-k=[only run tests matching EXPR]:expression:' \
                '--json[print the aggregated result as JSON]' \
                '*:path:_files'
            return
            ;;
        check|run|gc|test|lint)
            _arguments \
                '--json[print diagnostics as a JSON array]' \
                '--color[colorize diagnostics]:when:(auto always never)' \
                '--no-color[disable colors]' \
                '*:path:_files'
            return
            ;;
    esac

    _values 'option' $options
}

if [ "$funcstack[1]" = "_pyx" ]; then
    _pyx "$@"
else
    compdef _pyx pyx
fi
"#;

